"""Cuts the bundled fonts (Cairo is the interface font) down to the characters the app can ever show, and writes src/styles/fonts.css.

    ..\\ingest\\.venv\\Scripts\\python tools\\subset-fonts.py

Kept: core Arabic (letters, all tashkeel marks for reading lessons, Arabic-Indic digits, Arabic punctuation),
basic Latin, a few typographic marks. Dropped: extended Arabic for other languages (Urdu, Persian...),
presentation-form blocks (shaping uses OpenType features, which are kept), Cyrillic, Greek, Vietnamese.
Andika is the English reading font, so it keeps Latin only. Source: the @fontsource packages (SIL OFL 1.1).
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

APP = Path(__file__).resolve().parent.parent
NM = APP / 'node_modules' / '@fontsource'
OUT = APP / 'src' / 'fonts'
OUT.mkdir(parents=True, exist_ok=True)

ARABIC = 'U+0600-06FF,U+200C-200F,U+2010-2011,U+FD3E-FD3F'
LATIN = 'U+0020-007E,U+00A0,U+00AB,U+00BB,U+00D7,U+00F7,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2032-2033,U+20AC,U+2212'
LATIN_READ = LATIN + ',U+00C0-00FF'

# family, css weight, source woff2 files, unicodes, output name
FONTS = [
    ('Cairo', 500, ['cairo-arabic-500-normal', 'cairo-latin-500-normal'], ARABIC + ',' + LATIN, 'cairo-500'),
    ('Cairo', 700, ['cairo-arabic-700-normal', 'cairo-latin-700-normal'], ARABIC + ',' + LATIN, 'cairo-700'),
    ('Cairo', 800, ['cairo-arabic-800-normal', 'cairo-latin-800-normal'], ARABIC + ',' + LATIN, 'cairo-800'),
    ('Noto Naskh Arabic', 500, ['noto-naskh-arabic-arabic-500-normal'], ARABIC + ',U+0020-0040,U+00A0', 'naskh-500'),
    ('Andika', 400, ['andika-latin-400-normal'], LATIN_READ, 'andika-400'),
]


def compress(cps):
    out, start, prev = [], None, None
    for c in sorted(cps):
        if start is None:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append(f'U+{start:04X}' if start == prev else f'U+{start:04X}-{prev:04X}')
            start = prev = c
    if start is not None:
        out.append(f'U+{start:04X}' if start == prev else f'U+{start:04X}-{prev:04X}')
    return ', '.join(out)


def parse(ranges: str):
    cps = set()
    for part in ranges.split(','):
        a, _, b = part.replace('U+', '').partition('-')
        cps.update(range(int(a, 16), int(b or a, 16) + 1))
    return cps


css, report = ['/* Generated by tools/subset-fonts.py. Fonts: SIL Open Font License 1.1. Bundled for offline use. */'], []
for family, weight, sources, ranges, name in FONTS:
    wanted = parse(ranges)
    pkg = {'Lalezar': 'lalezar', 'Rubik': 'rubik', 'Cairo': 'cairo', 'Noto Naskh Arabic': 'noto-naskh-arabic', 'Andika': 'andika'}[family]
    before = 0
    parts = []
    for i, src in enumerate(sources):
        path = NM / pkg / 'files' / f'{src}.woff2'
        before += path.stat().st_size
        font = TTFont(path)
        have = set(font.getBestCmap().keys())
        keep = sorted(wanted & have)
        if not keep:
            continue
        opts = subset.Options()
        opts.flavor = 'woff2'
        opts.layout_features = ['*']          # keep Arabic shaping (init/medi/fina, ligatures, mark positioning)
        opts.name_IDs = ['*']
        opts.notdef_outline = True
        opts.hinting = False                   # smaller; phones render unhinted anyway
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=keep)
        sub.subset(font)
        out = OUT / f'{name}-{i}.woff2'
        font.flavor = 'woff2'
        font.save(out)
        urange = compress(keep)
        parts.append((out.name, urange, out.stat().st_size))
    for fname, urange, _ in parts:
        css.append(f"@font-face {{ font-family: '{family}'; font-style: normal; font-weight: {weight}; font-display: swap;\n"
                   f"  src: url('../fonts/{fname}') format('woff2');\n  unicode-range: {urange}; }}")
    after = sum(p[2] for p in parts)
    report.append(f'{family} {weight}: {before / 1024:.1f} KB -> {after / 1024:.1f} KB')

(APP / 'src' / 'styles' / 'fonts.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
print('\n'.join(report))
print('total:', round(sum(f.stat().st_size for f in OUT.glob('*.woff2')) / 1024, 1), 'KB in', OUT)
